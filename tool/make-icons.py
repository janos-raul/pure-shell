"""Generates every app icon from one geometry (the "framed" design).

    tool/make-icons.py                 regenerate everything
    tool/make-icons.py --preview OUT   write a mask preview sheet (circle, squircle,
                                       rounded square), nothing else

Writes (all committed):
  assets/icon/pure-shell-icon.svg        SVG master, 512 x 512, full bleed
  assets/icon/pure-shell-icon-512.png    Play Store icon, 512 x 512, opaque
  android/app/src/main/res/
    drawable/ic_launcher_foreground.xml  adaptive foreground (inside the 66 dp
                                         safe circle of the 108 dp canvas)
    drawable/ic_launcher_monochrome.xml  themed icon layer (Android 13+)
    drawable/ic_stat_session.xml         notification icon, white on transparent
    mipmap-*/ic_launcher.png             legacy fallbacks
    mipmap-anydpi-v26/ic_launcher.xml    adaptive icon
    values/colors.xml                    adaptive background colour

The PNGs are rendered with ImageMagick (`convert`) from the SVG.
Edit the constants below, run the script, commit the result.
"""
import math
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "android/app/src/main/res")
ICON_DIR = os.path.join(ROOT, "assets/icon")

BACKGROUND = "#0C0C0C"
GREEN = "#33FF66"

# ---- Master geometry, in a 512 x 512 canvas --------------------------------
SIZE = 512.0
FRAME_INSET = 0.10 * SIZE                     # 51.2
FRAME = SIZE - 2 * FRAME_INSET                # 409.6
FRAME_RADIUS = 0.16 * FRAME                   # 65.536
FRAME_STROKE = 0.03 * SIZE                    # 15.36
PROMPT_SCALE = 1.17            # the prompt is 17 % bigger than its first draft
_PROMPT_STROKE_0 = 0.07 * SIZE                  # 35.84 before scaling
_CHEVRON_0 = [(168, 176), (248, 256), (168, 336)]  # > left of centre
_UNDERSCORE_0 = [(280, 336), (352, 336)]           # _ to its lower right


def _scaled(points, stroke, about, to, s):
    """Scale a prompt (centreline points and stroke) by s around `about`, and
    put that point at `to`. The frame is not touched."""
    return [(to[0] + (x - about[0]) * s, to[1] + (y - about[1]) * s) for x, y in points], stroke * s


def _prompt_centre(points_lists, stroke):
    """Centre of the prompt's visible box (centreline plus half the stroke)."""
    xs = [x for pts in points_lists for x, _ in pts]
    ys = [y for pts in points_lists for _, y in pts]
    return ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2)


# The prompt stays centred in the frame (256, 256) after scaling.
_c0 = _prompt_centre([_CHEVRON_0, _UNDERSCORE_0], _PROMPT_STROKE_0)
CHEVRON, PROMPT_STROKE = _scaled(_CHEVRON_0, _PROMPT_STROKE_0, _c0, (SIZE / 2, SIZE / 2), PROMPT_SCALE)
UNDERSCORE, _ = _scaled(_UNDERSCORE_0, _PROMPT_STROKE_0, _c0, (SIZE / 2, SIZE / 2), PROMPT_SCALE)

# ---- Adaptive icon: 108 dp canvas, content inside the 66 dp safe circle ----
CANVAS_DP = 108.0
SAFE_DIAMETER_DP = 66.0


def adaptive_scale():
    """dp per master unit so the frame's outer edge stays inside the safe
    circle (the farthest point is on a rounded corner)."""
    half = FRAME / 2
    far = (half - FRAME_RADIUS) * math.sqrt(2) + FRAME_RADIUS + FRAME_STROKE / 2
    k = (SAFE_DIAMETER_DP / 2) / far
    return math.floor(k * 10000) / 10000  # a hair inside, round down


def num(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def rounded_rect_path(x0, y0, x1, y1, r):
    return (
        f"M{num(x0 + r)},{num(y0)} H{num(x1 - r)} "
        f"A{num(r)},{num(r)} 0 0 1 {num(x1)},{num(y0 + r)} V{num(y1 - r)} "
        f"A{num(r)},{num(r)} 0 0 1 {num(x1 - r)},{num(y1)} H{num(x0 + r)} "
        f"A{num(r)},{num(r)} 0 0 1 {num(x0)},{num(y1 - r)} V{num(y0 + r)} "
        f"A{num(r)},{num(r)} 0 0 1 {num(x0 + r)},{num(y0)} Z"
    )


def poly_path(points):
    head, *rest = points
    return "M%s,%s " % (num(head[0]), num(head[1])) + " ".join(
        "L%s,%s" % (num(x), num(y)) for x, y in rest
    )


def vector_xml(size_dp, viewport, parts, color):
    """parts: list of (pathData, strokeWidth, round). Stroke only, no fill."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/make-icons.py: edit the script, not this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{num(size_dp)}dp"',
        f'    android:height="{num(size_dp)}dp"',
        f'    android:viewportWidth="{num(viewport)}"',
        f'    android:viewportHeight="{num(viewport)}">',
    ]
    for data, stroke, rnd in parts:
        lines.append("    <path")
        lines.append(f'        android:pathData="{data}"')
        lines.append(f'        android:strokeColor="{color}"')
        lines.append(f'        android:strokeWidth="{num(stroke)}"')
        if rnd:
            lines.append('        android:strokeLineCap="round"')
            lines.append('        android:strokeLineJoin="round"')
        lines[-1] += " />"
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def master_svg():
    fx = FRAME_INSET
    chev = " L".join(f"{num(x)} {num(y)}" for x, y in CHEVRON)
    under = " L".join(f"{num(x)} {num(y)}" for x, y in UNDERSCORE)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!--
  Pure-Shell app icon, the "framed" design. Generated by tool/make-icons.py,
  which also derives every other icon from the same geometry.

  512 x 512, full bleed:
    background  {BACKGROUND}
    frame       rounded square inset 10 %, corner radius 16 % of the frame,
                stroke 3 % of the icon, {GREEN}
    prompt      chevron and underscore, stroke 7 %, round caps and joins,
                {GREEN}; chevron left of centre, underscore to its lower right
-->
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <rect width="512" height="512" fill="{BACKGROUND}"/>
  <rect x="{num(fx)}" y="{num(fx)}" width="{num(FRAME)}" height="{num(FRAME)}" rx="{num(FRAME_RADIUS)}" ry="{num(FRAME_RADIUS)}"
        fill="none" stroke="{GREEN}" stroke-width="{num(FRAME_STROKE)}"/>
  <g fill="none" stroke="{GREEN}" stroke-width="{num(PROMPT_STROKE)}"
     stroke-linecap="round" stroke-linejoin="round">
    <path d="M{chev}"/>
    <path d="M{under}"/>
  </g>
</svg>
"""


def adaptive_parts():
    k = adaptive_scale()

    def t(p):
        return (CANVAS_DP / 2 + (p[0] - SIZE / 2) * k, CANVAS_DP / 2 + (p[1] - SIZE / 2) * k)

    x0, y0 = t((FRAME_INSET, FRAME_INSET))
    x1, y1 = t((SIZE - FRAME_INSET, SIZE - FRAME_INSET))
    return [
        (rounded_rect_path(x0, y0, x1, y1, FRAME_RADIUS * k), FRAME_STROKE * k, False),
        (poly_path([t(p) for p in CHEVRON]), PROMPT_STROKE * k, True),
        (poly_path([t(p) for p in UNDERSCORE]), PROMPT_STROKE * k, True),
    ], k


def notification_parts():
    """24 dp, simplified so it reads small: a thicker frame and prompt, the
    prompt scaled like the master's."""
    chevron0 = [(7.6, 8.4), (11.2, 12), (7.6, 15.6)]
    underscore0 = [(13.2, 15.6), (16.4, 15.6)]
    centre = (12, 12)
    chevron, stroke = _scaled(chevron0, 2.0, centre, centre, PROMPT_SCALE)
    underscore, _ = _scaled(underscore0, 2.0, centre, centre, PROMPT_SCALE)
    return [
        (rounded_rect_path(3, 3, 21, 21, 4.2), 1.7, False),
        (poly_path(chevron), stroke, True),
        (poly_path(underscore), stroke, True),
    ]


def render_png(svg, out, size, opaque=False):
    cmd = ["convert", "-background", "none", "-density", "384", svg,
           "-resize", f"{size}x{size}", "-depth", "8"]
    if opaque:
        cmd += ["-alpha", "off"]
    subprocess.run(cmd + ["PNG24:" + out], check=True)
    print("wrote", os.path.relpath(out, ROOT))


# The Android icon masks, in a 100 x 100 box (AOSP's config_icon_mask and the
# shape overlays). The mask is applied to the central 72 dp of the 108 dp canvas.
MASKS = [
    ("circle", "M50,0 A50,50 0 1 1 50,100 A50,50 0 1 1 50,0 Z"),
    ("squircle", "M50,0 C10,0 0,10 0,50 C0,90 10,100 50,100 C90,100 100,90 100,50 C100,10 90,0 50,0 Z"),
    ("rounded square", "M50,0 L92,0 C96.42,0 100,3.58 100,8 L100,92 C100,96.42 96.42,100 92,100 "
                       "L8,100 C3.58,100 0,96.42 0,92 L0,8 C0,3.58 3.58,0 8,0 Z"),
]


def preview(out):
    """A sheet of the adaptive icon under each mask, big and launcher-sized,
    rendered from the same layers as the real icon (not from a device)."""
    from PIL import Image, ImageDraw  # only needed for this preview

    parts, _ = adaptive_parts()
    layers = []
    for data, stroke, rnd in parts:
        cap = ' stroke-linecap="round" stroke-linejoin="round"' if rnd else ""
        layers.append(f'<path d="{data}" fill="none" stroke="{GREEN}" stroke-width="{num(stroke)}"{cap}/>')
    tmp = out + ".tmp"
    # The visible area is the central 72 dp of the 108 dp canvas.
    icon_svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="576" height="576" viewBox="18 18 72 72">'
                f'<rect x="0" y="0" width="108" height="108" fill="{BACKGROUND}"/>' + "".join(layers) + "</svg>")
    with open(tmp + ".svg", "w") as f:
        f.write(icon_svg)
    subprocess.run(["convert", "-background", "none", "-density", "96", tmp + ".svg", "PNG24:" + tmp + ".png"], check=True)
    icon = Image.open(tmp + ".png").convert("RGB")
    sheet = Image.new("RGB", (40 + 330 * len(MASKS), 700), "#D9DAE0")
    draw = ImageDraw.Draw(sheet)
    x = 40
    for name, path in MASKS:
        mask_svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="576" height="576" viewBox="0 0 100 100">'
                    f'<rect width="100" height="100" fill="black"/><path d="{path}" fill="white"/></svg>')
        with open(tmp + ".svg", "w") as f:
            f.write(mask_svg)
        subprocess.run(["convert", "-density", "96", tmp + ".svg", "-colorspace", "Gray", "PNG8:" + tmp + ".png"], check=True)
        mask = Image.open(tmp + ".png").convert("L")
        for size, y in ((288, 60), (72, 400)):
            sheet.paste(icon.resize((size, size), Image.LANCZOS), (x, y), mask.resize((size, size), Image.LANCZOS))
        draw.text((x, 500), name, fill="#222222")
        x += 330
    # The notification icon (white on the status bar's dark) at 24 px, at the
    # ~63 px it takes on a 2.6x phone, and large.
    n = []
    for data, stroke, rnd in notification_parts():
        cap = ' stroke-linecap="round" stroke-linejoin="round"' if rnd else ""
        n.append(f'<path d="{data}" fill="none" stroke="#FFFFFF" stroke-width="{num(stroke)}"{cap}/>')
    with open(tmp + ".svg", "w") as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" width="384" height="384" viewBox="0 0 24 24">' + "".join(n) + "</svg>")
    subprocess.run(["convert", "-background", "none", "-density", "96", tmp + ".svg", "PNG32:" + tmp + ".png"], check=True)
    note = Image.open(tmp + ".png").convert("RGBA")
    draw.rectangle((0, 560, sheet.width, 700), fill="#2B2B2B")
    nx = 40
    for size in (24, 63, 96):
        sheet.paste(note.resize((size, size), Image.LANCZOS), (nx, 575), note.resize((size, size), Image.LANCZOS))
        nx += size + 40
    draw.text((40, 680), "notification icon at 24 px, 63 px (2.6x phone), 96 px", fill="#DDDDDD")
    sheet.save(out)
    for ext in (".svg", ".png"):
        os.remove(tmp + ext)
    print("wrote", out)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        return preview(sys.argv[2])
    # Master and Play Store icon.
    svg = os.path.join(ICON_DIR, "pure-shell-icon.svg")
    write(svg, master_svg())
    render_png(svg, os.path.join(ICON_DIR, "pure-shell-icon-512.png"), 512, opaque=True)

    # Adaptive icon.
    parts, k = adaptive_parts()
    print("adaptive scale: %.4f dp per unit (frame %.1f dp wide)"
          % (k, (FRAME + FRAME_STROKE) * k))
    write(os.path.join(RES, "drawable/ic_launcher_foreground.xml"),
          vector_xml(CANVAS_DP, CANVAS_DP, parts, GREEN))
    write(os.path.join(RES, "drawable/ic_launcher_monochrome.xml"),
          vector_xml(CANVAS_DP, CANVAS_DP, parts, "#FFFFFFFF"))
    write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by tool/make-icons.py -->\n"
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '  <background android:drawable="@color/ic_launcher_background"/>\n'
          '  <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
          '  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
          "</adaptive-icon>\n")
    write(os.path.join(RES, "values/colors.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n'
          "<resources>\n"
          f'    <color name="ic_launcher_background">{BACKGROUND}</color>\n'
          "</resources>\n")

    # Notification icon.
    write(os.path.join(RES, "drawable/ic_stat_session.xml"),
          vector_xml(24, 24, notification_parts(), "#FFFFFFFF"))

    # Legacy fallbacks (the app needs Android 11, so launchers use the adaptive
    # icon; these only keep the old PNG slots from showing a stale icon).
    for dens, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        render_png(svg, os.path.join(RES, f"mipmap-{dens}/ic_launcher.png"), px, opaque=True)


if __name__ == "__main__":
    sys.exit(main())
